#!/usr/bin/env node
/**
 * Install canonical prek-managed git hooks for this repository.
 */

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const PREK_HOOK_MARKER = "# File generated by prek: https://github.com/j178/prek";
const PREK_HOOK_PATCH = [
	"# Keep prek cache/logs in repo-local .git to avoid home-dir sandbox write failures",
	'PREK_HOME="${PREK_HOME:-$HERE/../.cache/prek}"',
	'mkdir -p "$PREK_HOME" 2>/dev/null || true',
	"export PREK_HOME",
	"",
].join("\n");

function tryRead(command, args) {
	try {
		return execFileSync(command, args, {
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
		}).trim();
	} catch {
		return "";
	}
}

function readLegacyLocalHooksPath() {
	return tryRead("git", ["config", "--local", "--get", "core.hooksPath"]);
}

function clearLegacyLocalHooksPath(configuredPath) {
	if (!configuredPath) {
		return;
	}

	console.info(`Removing legacy local core.hooksPath: ${configuredPath}`);
	execFileSync("git", ["config", "--local", "--unset", "core.hooksPath"], {
		stdio: "ignore",
	});
}

function restoreLegacyLocalHooksPath(configuredPath) {
	if (!configuredPath) {
		return;
	}
	execFileSync("git", ["config", "--local", "core.hooksPath", configuredPath], {
		stdio: "ignore",
	});
}

function patchInstalledPrekHooks() {
	const hooksDir = resolve(process.cwd(), ".git/hooks");
	if (!existsSync(hooksDir)) {
		return 0;
	}

	let patchedCount = 0;
	for (const hookName of readdirSync(hooksDir)) {
		const hookPath = resolve(hooksDir, hookName);
		let hookContent = "";
		try {
			hookContent = readFileSync(hookPath, "utf8");
		} catch {
			continue;
		}

		if (!hookContent.includes(PREK_HOOK_MARKER)) {
			continue;
		}
		if (hookContent.includes('PREK_HOME="${PREK_HOME:-$HERE/../.cache/prek}"')) {
			continue;
		}

		const patched = hookContent.replace(
			'fi\n\nexec "$PREK" hook-impl',
			`fi\n\n${PREK_HOOK_PATCH}exec "$PREK" hook-impl`,
		);
		if (patched === hookContent) {
			continue;
		}

		writeFileSync(hookPath, patched);
		patchedCount += 1;
	}

	return patchedCount;
}

function main() {
	const legacyHooksPath = readLegacyLocalHooksPath();
	clearLegacyLocalHooksPath(legacyHooksPath);

	try {
		execFileSync("prek", ["install"], { stdio: "inherit" });
		const patchedCount = patchInstalledPrekHooks();
		if (patchedCount > 0) {
			console.info(`Patched ${patchedCount} prek hook shim(s) with repo-local PREK_HOME`);
		}
		console.info("Installed canonical prek hooks");
	} catch (error) {
		try {
			restoreLegacyLocalHooksPath(legacyHooksPath);
		} catch {
			console.error("Error: failed to restore previous core.hooksPath after hook install failure.");
		}

		if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
			console.error("Error: `prek` is not available; hook installation failed.");
			console.error("Install `prek` and re-run scripts/setup-git-hooks.js.");
		} else {
			console.error("Error: `prek install` failed.");
		}
		process.exit(1);
	}
}

main();
